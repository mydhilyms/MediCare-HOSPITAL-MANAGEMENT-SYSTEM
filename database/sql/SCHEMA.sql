CREATE VIEW v_appointments_by_branch AS
SELECT b.branch_id, b.location, COUNT(a.appointment_id) AS appointments
FROM branch b LEFT JOIN appointment a ON a.branch_id = b.branch_id
GROUP BY b.branch_id, b.location;

CREATE VIEW v_pharmacy_low_stock AS
SELECT ph.pharmacy_id, ph.branch_id, med.medicine_id, med.name AS medicine,
       i.stock_quantity, i.reorder_level, i.price
FROM pharmacy_inventory i
JOIN pharmacy ph ON ph.pharmacy_id = i.pharmacy_id
JOIN medicine med ON med.medicine_id = i.medicine_id
WHERE i.stock_quantity <= i.reorder_level;

