-- salary and constraints
CREATE TABLE salary (
    salary_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    doctor_id INTEGER REFERENCES doctor(doctor_id),
    nurse_id INTEGER REFERENCES nurse(nurse_id),
    staff_id INTEGER REFERENCES staff(staff_id),
    pay_structure_id INTEGER NOT NULL REFERENCES pay_structure(pay_structure_id),
