CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;
CREATE SCHEMA IF NOT EXISTS hms;
SET search_path TO hms, public;

-- Hospital people and appointments

-- branch schema
CREATE TABLE branch (
    branch_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location VARCHAR(150) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive'))
);

-- dept
CREATE TABLE department (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL,
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    status VARCHAR(10) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    UNIQUE (branch_id, department_name)
);

-- doctor
CREATE TABLE doctor (
    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    specialization VARCHAR(120),
    phone VARCHAR(25),
    department_id INTEGER NOT NULL REFERENCES department(department_id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- doctor-shift rel 
-- foreign key doctor,branch_id
CREATE TABLE doctor_shift (
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    shift_start TIMESTAMP NOT NULL,
    shift_end TIMESTAMP NOT NULL,
    PRIMARY KEY (doctor_id, branch_id, shift_start),
    CHECK (shift_end>shift_start),
    CONSTRAINT doctor_shift_no_overlap EXCLUDE USING gist (
        doctor_id WITH =,
        tsrange(shift_start, shift_end, '[)') WITH &&
    )
);

-- patient info
CREATE TABLE patient (
    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    dob DATE,
    gender VARCHAR(20),
    street VARCHAR(150),
    city VARCHAR(100),
    state VARCHAR(100),
    pin_code VARCHAR(12),
    phone VARCHAR(25)
);

-- appointment (appointment time if fixed 30 mins)
CREATE TABLE appointment (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    appointment_date DATE NOT NULL,
    appointment_time TIME NOT NULL,
    token_no INTEGER NOT NULL CHECK (token_no > 0),
    status VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    UNIQUE (branch_id, appointment_date, token_no),
    CONSTRAINT appointment_doctor_no_overlap EXCLUDE USING gist (
        doctor_id WITH =,
        tsrange(appointment_date + appointment_time,appointment_date + appointment_time + INTERVAL '30 minutes', '[)') WITH &&
    ) WHERE (status IN ('pending','confirmed'))
);

-- nurse schema
CREATE TABLE nurse (
    nurse_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    shift VARCHAR(50),
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id)
);

-- staff schema
CREATE TABLE staff (
    staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    role VARCHAR(80) NOT NULL,
    shift VARCHAR(50),
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id)
);

-- nurse assigned to patient (fkey)
CREATE TABLE nurse_assignment (
    nurse_id INTEGER NOT NULL REFERENCES nurse(nurse_id),
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    assignment_date DATE NOT NULL,
    PRIMARY KEY (nurse_id, patient_id, assignment_date)
);

-- staff assigned to patient (fkey) (not null are fixed at frontend form validation)
CREATE TABLE staff_assignment (
    staff_id INTEGER NOT NULL REFERENCES staff(staff_id),
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    assignment_date DATE NOT NULL,
    PRIMARY KEY (staff_id, patient_id, assignment_date)
);

-- Rooms, clinical services and pharmacy
-- room management (enum toggleable states)
CREATE TABLE room (
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    room_no VARCHAR(20) NOT NULL,
    room_type VARCHAR(30) NOT NULL
        CHECK (room_type IN ('general', 'private', 'icu')),
    critical_care_monitoring BOOLEAN NOT NULL DEFAULT FALSE,
    availability_status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (availability_status IN ('available', 'occupied', 'maintenance', 'reserved')),
    PRIMARY KEY (branch_id, room_no)
);

-- admission of patient with room
CREATE TABLE admission (
    admission_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    branch_id INTEGER NOT NULL,
    room_no VARCHAR(20) NOT NULL,
    admit_date_time TIMESTAMP NOT NULL,
    discharge_date_time TIMESTAMP,
    FOREIGN KEY (branch_id, room_no) REFERENCES room(branch_id, room_no),
    CHECK (discharge_date_time IS NULL OR discharge_date_time > admit_date_time),
    CONSTRAINT admission_room_no_overlap EXCLUDE USING gist (
        branch_id WITH =, room_no WITH =,
        tsrange(admit_date_time,
                COALESCE(discharge_date_time, 'infinity'::timestamp), '[)') WITH &&
    ),
    CONSTRAINT admission_patient_no_overlap EXCLUDE USING gist (
        patient_id WITH =,
        tsrange(admit_date_time,
                COALESCE(discharge_date_time, 'infinity'::timestamp), '[)') WITH &&
    )
);

-- prescription (doctor-patient , prescription id is the pkey)
CREATE TABLE prescription (
    prescription_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    prescription_date DATE NOT NULL
);

-- medicine Price/quantity belong to PharmacyInventory, not Medicine.
CREATE TABLE medicine (
    medicine_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL
);

-- details
CREATE TABLE prescription_detail (
    prescription_id INTEGER NOT NULL REFERENCES prescription(prescription_id),
    medicine_id INTEGER NOT NULL REFERENCES medicine(medicine_id),
    dosage VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (prescription_id, medicine_id)
);

-- pharmacy ref branch
CREATE TABLE pharmacy (
    pharmacy_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id)
);

-- assosiated with a (pharmacy,medicine) (bussiness 3)
CREATE TABLE pharmacy_inventory (
    pharmacy_id INTEGER NOT NULL REFERENCES pharmacy(pharmacy_id),
    medicine_id INTEGER NOT NULL REFERENCES medicine(medicine_id),
    stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    PRIMARY KEY (pharmacy_id, medicine_id)
);

-- lab results and stuff
CREATE TABLE lab_result (
    lab_result_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    test_type VARCHAR(120) NOT NULL,
    order_date DATE NOT NULL,
    result_date DATE,
    result_details TEXT,
    CHECK (result_date IS NULL OR result_date >= order_date)
);

-- Operation theatre ,billing and ...
CREATE TABLE operation_theatre (
    ot_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'busy', 'maintenance', 'inactive'))
);

-- scedule
CREATE TABLE ot_schedule (
    ot_schedule_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ot_id INTEGER NOT NULL REFERENCES operation_theatre(ot_id),
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    nurse_id INTEGER NOT NULL REFERENCES nurse(nurse_id),
    procedure VARCHAR(200) NOT NULL,
    schedule_start TIMESTAMP NOT NULL,
    schedule_end TIMESTAMP NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'completed', 'cancelled')),
    CHECK (schedule_end > schedule_start),
    CONSTRAINT ot_no_overlap EXCLUDE USING gist (
        ot_id WITH =, tsrange(schedule_start, schedule_end, '[)') WITH &&
    ) WHERE (status <> 'cancelled'),
    CONSTRAINT ot_doctor_no_overlap EXCLUDE USING gist (
        doctor_id WITH =, tsrange(schedule_start, schedule_end, '[)') WITH &&
    ) WHERE (status <> 'cancelled'),
    CONSTRAINT ot_nurse_no_overlap EXCLUDE USING gist (
        nurse_id WITH =, tsrange(schedule_start, schedule_end, '[)') WITH &&
    ) WHERE (status <> 'cancelled'),
    CONSTRAINT ot_patient_no_overlap EXCLUDE USING gist (
        patient_id WITH =, tsrange(schedule_start, schedule_end, '[)') WITH &&
    ) WHERE (status <> 'cancelled')
);

-- equipment stuff
