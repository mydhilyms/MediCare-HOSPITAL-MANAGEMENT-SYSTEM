-- Transaction-safe dispensing: decrements LOCAL pharmacy stock only.
-- The document does not define a dispensing-history table, so this function
-- updates the stock but does not create a historical dispensing record.
CREATE FUNCTION dispense_medicine(p_pharmacy_id INTEGER,
                                  p_medicine_id INTEGER,
                                  p_quantity INTEGER) RETURNS INTEGER
LANGUAGE plpgsql AS $$
DECLARE v_stock INTEGER;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION 'Dispensed quantity must be positive';
    END IF;
    UPDATE hms.pharmacy_inventory
       SET stock_quantity = stock_quantity - p_quantity
     WHERE pharmacy_id = p_pharmacy_id
       AND medicine_id = p_medicine_id
       AND stock_quantity >= p_quantity
    RETURNING stock_quantity INTO v_stock;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Medicine not stocked or insufficient pharmacy inventory';
    END IF;
    RETURN v_stock;
END;
$$;
