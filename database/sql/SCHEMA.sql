-- Fixing bussiness rules using sql
CREATE FUNCTION check_appointment_rules() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_department_id INTEGER;
    v_start TIMESTAMP;
    v_end TIMESTAMP;
BEGIN
    IF NEW.status NOT IN ('pending', 'confirmed') THEN
        RETURN NEW;
    END IF;

    SELECT d.department_id INTO v_department_id
      FROM hms.doctor d
      JOIN hms.department dep ON dep.department_id = d.department_id
      JOIN hms.branch b ON b.branch_id = NEW.branch_id
     WHERE d.doctor_id = NEW.doctor_id
       AND d.is_active = TRUE
       AND dep.status = 'active' AND b.status = 'active';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Doctor primary department or selected branch is inactive';
    END IF;

    v_start := NEW.appointment_date + NEW.appointment_time;
    v_end := v_start + INTERVAL '30 minutes';
    IF NOT EXISTS (
        SELECT 1 FROM hms.doctor_shift ds
         WHERE ds.doctor_id = NEW.doctor_id AND ds.branch_id = NEW.branch_id
           AND ds.shift_start <= v_start AND ds.shift_end >= v_end
    ) THEN
        RAISE EXCEPTION 'Appointment must fit a shift in this branch';
    END IF;

    -- Serialize bookings for the same patient, including concurrent inserts.
    PERFORM pg_advisory_xact_lock(9381, NEW.patient_id);
    IF EXISTS (
        SELECT 1 FROM hms.appointment a
        JOIN hms.doctor existing_doctor ON existing_doctor.doctor_id = a.doctor_id
        WHERE a.patient_id = NEW.patient_id
          AND existing_doctor.department_id = v_department_id
          AND a.status IN ('pending', 'confirmed')
          AND a.appointment_id IS DISTINCT FROM NEW.appointment_id
          AND tsrange(a.appointment_date + a.appointment_time,
                      a.appointment_date + a.appointment_time + INTERVAL '30 minutes', '[)')
              && tsrange(v_start, v_end, '[)')
    ) THEN
        RAISE EXCEPTION 'Patient has overlapping consultations in the same department';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER appointment_business_rules
BEFORE INSERT OR UPDATE OF patient_id, doctor_id, branch_id,
                           appointment_date, appointment_time, status
ON appointment FOR EACH ROW EXECUTE FUNCTION check_appointment_rules();

CREATE FUNCTION check_ot_nurse_branch() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM hms.operation_theatre ot JOIN hms.nurse n ON n.nurse_id = NEW.nurse_id
        WHERE ot.ot_id = NEW.ot_id AND ot.branch_id = n.branch_id
    ) THEN
        RAISE EXCEPTION 'OT and assigned nurse must be in the same branch';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER ot_branch_rule
BEFORE INSERT OR UPDATE OF ot_id, nurse_id ON ot_schedule
FOR EACH ROW EXECUTE FUNCTION check_ot_nurse_branch();

CREATE FUNCTION check_bill_operation_complete() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_appointment hms.appointment%ROWTYPE;
    v_ot hms.ot_schedule%ROWTYPE;
    v_ot_branch INTEGER;
BEGIN
    SELECT * INTO STRICT v_appointment
      FROM hms.appointment WHERE appointment_id = NEW.appointment_id;
    IF NEW.branch_id <> v_appointment.branch_id THEN
        RAISE EXCEPTION 'Bill branch must match appointment branch';
    END IF;
    IF NEW.ot_schedule_id IS NOT NULL THEN
        SELECT * INTO STRICT v_ot FROM hms.ot_schedule
         WHERE ot_schedule_id = NEW.ot_schedule_id;
        SELECT branch_id INTO STRICT v_ot_branch
          FROM hms.operation_theatre WHERE ot_id = v_ot.ot_id;
        IF v_ot.status <> 'completed' OR v_ot_branch <> NEW.branch_id
           OR v_ot.patient_id <> v_appointment.patient_id
           OR v_ot.doctor_id <> v_appointment.doctor_id THEN
            RAISE EXCEPTION 'Operation bill requires a completed, matching OT schedule';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER bill_operation_rule
BEFORE INSERT OR UPDATE OF appointment_id, branch_id, ot_schedule_id ON bill
FOR EACH ROW EXECUTE FUNCTION check_bill_operation_complete();

CREATE FUNCTION check_salary_employee_type() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE v_type VARCHAR(10);
BEGIN
    SELECT employee_type INTO v_type FROM hms.pay_structure
     WHERE pay_structure_id = NEW.pay_structure_id AND status = 'active';
    IF v_type IS NULL OR
       (NEW.doctor_id IS NOT NULL AND v_type <> 'doctor') OR
       (NEW.nurse_id IS NOT NULL AND v_type <> 'nurse') OR
       (NEW.staff_id IS NOT NULL AND v_type <> 'staff') THEN
        RAISE EXCEPTION 'Pay structure does not match the salary employee type';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER salary_type_rule
BEFORE INSERT OR UPDATE OF doctor_id, nurse_id, staff_id, pay_structure_id
ON salary FOR EACH ROW EXECUTE FUNCTION check_salary_employee_type();

CREATE FUNCTION check_salary_shift_log() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    s hms.salary%ROWTYPE;
    l hms.shift_log%ROWTYPE;
BEGIN
    SELECT * INTO STRICT s FROM hms.salary WHERE salary_id = NEW.salary_id;
    SELECT * INTO STRICT l FROM hms.shift_log WHERE shift_log_id = NEW.shift_log_id;
    IF s.branch_id <> l.branch_id OR
       s.doctor_id IS DISTINCT FROM l.doctor_id OR
       s.nurse_id IS DISTINCT FROM l.nurse_id OR
       s.staff_id IS DISTINCT FROM l.staff_id OR
       date_trunc('month', l.shift_date::timestamp)::date <> s.pay_month OR
       l.status <> 'completed' THEN
        RAISE EXCEPTION 'Salary must link to matching completed employee shifts in its month';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER salary_shift_log_rule
BEFORE INSERT OR UPDATE ON salary_shift_log
FOR EACH ROW EXECUTE FUNCTION check_salary_shift_log();

