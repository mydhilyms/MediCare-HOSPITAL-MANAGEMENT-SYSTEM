-- Revenue summary( month)
CREATE OR REPLACE VIEW v_revenue_summary AS
SELECT
    date_trunc('month', bill_date::TIMESTAMP) AS month_start,
    COUNT(*) AS bill_count,
    SUM(amount) AS total_amount,
    SUM(CASE WHEN payment_status = 'paid' THEN amount ELSE 0 END) AS paid_amount
FROM hms.bill
GROUP BY date_trunc('month', bill_date::TIMESTAMP);

-- Pharmacy stock alert view
CREATE OR REPLACE VIEW v_pharmacy_alerts AS
SELECT
    ph.pharmacy_id,
    b.location AS branch_location,
    med.medicine_id,
    med.name AS medicine_name,
    i.stock_quantity,
    i.reorder_level,
    i.price
FROM hms.pharmacy_inventory i
JOIN hms.pharmacy ph ON ph.pharmacy_id = i.pharmacy_id
JOIN hms.branch b ON b.branch_id = ph.branch_id
JOIN hms.medicine med ON med.medicine_id = i.medicine_id
WHERE i.stock_quantity <= i.reorder_level;
