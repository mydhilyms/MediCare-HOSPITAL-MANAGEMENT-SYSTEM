-- fn to retrieve data for stats and graphs
CREATE OR REPLACE FUNCTION get_dashboard_stats()
RETURNS TABLE (
    total_patients        BIGINT,
    active_patients       BIGINT,
    total_doctors         BIGINT,
    upcoming_appointments BIGINT,
    pending_bills         BIGINT,
    revenue               NUMERIC,
    total_admissions      BIGINT,
    occupancy_pct         NUMERIC
) LANGUAGE plpgsql AS $$
BEGIN
    RETURN QUERY
    SELECT
        (SELECT COUNT(*) FROM hms.patient)::BIGINT,
        (SELECT COUNT(*) FROM hms.admission WHERE discharge_date_time IS NULL)::BIGINT,
        (SELECT COUNT(*) FROM hms.doctor WHERE is_active)::BIGINT,
        (SELECT COUNT(*) FROM hms.appointment WHERE status IN ('pending','confirmed') AND appointment_date >= CURRENT_DATE)::BIGINT,
        (SELECT COUNT(*) FROM hms.bill WHERE payment_status IN ('unpaid','partial'))::BIGINT,
        COALESCE((SELECT SUM(amount) FROM hms.bill WHERE payment_status = 'paid'), 0::NUMERIC),
        (SELECT COUNT(*) FROM hms.admission)::BIGINT,
        CASE
            WHEN (SELECT COUNT(*) FROM hms.room) = 0 THEN 0::NUMERIC
            ELSE ROUND(
                (SELECT COUNT(*) FROM hms.room WHERE availability_status = 'occupied')::NUMERIC
                / (SELECT COUNT(*) FROM hms.room)::NUMERIC * 100, 1
            )
        END;
END;
$$;

-- accumulate sum of monthly revenue (Additional stuff)
CREATE OR REPLACE FUNCTION get_monthly_revenue(p_months INTEGER DEFAULT 6)
RETURNS TABLE (
    month_name TEXT,
    revenue    NUMERIC
) LANGUAGE plpgsql AS $$
BEGIN
    RETURN QUERY
    SELECT
        TO_CHAR(months.m, 'Mon YYYY') AS month_name,
        COALESCE(SUM(b.amount), 0::NUMERIC) AS revenue
    FROM generate_series(
        date_trunc('month', CURRENT_DATE) - ((p_months - 1) || ' months')::INTERVAL,
        date_trunc('month', CURRENT_DATE),
        '1 month'::INTERVAL
    ) AS months(m)
    LEFT JOIN hms.bill b
        ON date_trunc('month', b.bill_date::TIMESTAMP) = months.m
        AND b.payment_status = 'paid'
    GROUP BY months.m
    ORDER BY months.m;
END;
$$;

-- dept data
CREATE OR REPLACE FUNCTION get_department_load()
RETURNS TABLE (
    department_name   VARCHAR,
    doctor_count      BIGINT,
    appointment_count BIGINT,
    load_pct          NUMERIC
) LANGUAGE plpgsql AS $$
DECLARE
    v_total_appts BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_total_appts
      FROM hms.appointment WHERE status IN ('pending','confirmed');

    RETURN QUERY
    SELECT
        dep.department_name,
        COUNT(DISTINCT doc.doctor_id)::BIGINT AS doctor_count,
        COUNT(DISTINCT a.appointment_id)::BIGINT AS appointment_count,
        CASE
            WHEN v_total_appts = 0 THEN 0::NUMERIC
            ELSE ROUND(COUNT(DISTINCT a.appointment_id)::NUMERIC / v_total_appts::NUMERIC * 100, 1)
        END AS load_pct
    FROM hms.department dep
    LEFT JOIN hms.doctor doc ON doc.department_id = dep.department_id
    LEFT JOIN hms.appointment a ON a.doctor_id = doc.doctor_id
        AND a.status IN ('pending','confirmed')
    GROUP BY dep.department_name
    ORDER BY appointment_count DESC;
END;
$$;


